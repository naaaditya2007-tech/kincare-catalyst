"use client";

import React, { useState } from "react";
import { motion, AnimatePresence } from "framer-motion";
import { X, Copy, Check, Printer, FileText, AlertCircle } from "lucide-react";
import { KinCareState } from "@/types/kincare";

interface ClinicalBriefModalProps {
  isOpen: boolean;
  onClose: () => void;
  state: KinCareState;
}

export const ClinicalBriefModal: React.FC<ClinicalBriefModalProps> = ({
  isOpen,
  onClose,
  state,
}) => {
  const [copied, setCopied] = useState(false);
  const elder = state.elderProfile;
  const appt = state.appointments[0];

  if (!isOpen) return null;

  const apptDateFormatted = appt
    ? new Date(appt.dateTime).toLocaleDateString("en-US", {
        weekday: "short",
        month: "short",
        day: "numeric",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit",
      })
    : "Upcoming Review";

  const generatePlainTextSummary = () => {
    const medLines = state.medications
      .filter((m) => m.active)
      .map(
        (m, idx) =>
          `  ${idx + 1}. ${m.name} - ${m.dosage} (${m.form}) | Times: ${m.scheduledTimes.join(", ")} | ${m.instructions}`
      )
      .join("\n");

    const checklistLines = (appt?.checklistQuestions || [])
      .map((q, idx) => `  [ ] Q${idx + 1}: ${q}`)
      .join("\n");

    return `==========================================================
KINCARE CLINICAL BRIEF & DOCTOR VISIT SUMMARY
==========================================================
PATIENT INFORMATION:
- Name: ${elder.name}
- Age: ${elder.age} | Blood Group: ${elder.bloodGroup}
- Known Allergies: ${elder.allergies.join(", ")} (CRITICAL: DO NOT PRESCRIBE PENICILLIN)
- Primary Diagnoses: ${elder.conditions.join(", ")}
- Emergency Contact: Anita Iyer (Daughter) - ${elder.emergencyPhone}

APPOINTMENT CONTEXT:
- Physician: ${appt?.doctorName || "Dr. Arvind Swaminathan"} (${appt?.specialty || "Cardiology"})
- Facility: ${appt?.hospital || "Apollo Speciality Hospitals"}
- Date & Time: ${apptDateFormatted}
- OPD Location: ${appt?.location || "Main OPD"}
- Clinical Objective: ${appt?.notes || "Routine follow up"}

ACTIVE MEDICATIONS (${state.medications.filter((m) => m.active).length} Prescriptions):
${medLines}

CARE CIRCLE COLLABORATIVE DISCUSSION CHECKLIST:
${checklistLines}

RECENT ADHERENCE NOTE:
Elder reported occasional lightheadedness following morning antihypertensive dose. Family requests evaluation of peak vasodilation timing.
==========================================================
Generated by KinCare Platform`;
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(generatePlainTextSummary());
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <AnimatePresence>
      <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/40 backdrop-blur-xs">
        <motion.div
          initial={{ opacity: 0, scale: 0.95, y: 10 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.95, y: 10 }}
          className="bg-white rounded-2xl border border-slate-200 shadow-2xl max-w-2xl w-full p-6 sm:p-8 relative max-h-[90vh] overflow-y-auto"
        >
          {/* Close */}
          <button
            onClick={onClose}
            className="absolute top-5 right-5 p-2 text-slate-400 hover:text-slate-600 rounded-full hover:bg-slate-100 transition print:hidden"
          >
            <X className="w-5 h-5" />
          </button>

          {/* Top Actions: Copy & Print */}
          <div className="flex items-center justify-between border-b border-slate-200 pb-4 mb-6">
            <div className="flex items-center gap-3">
              <div className="w-10 h-10 rounded-xl bg-slate-900 text-white flex items-center justify-center">
                <FileText className="w-5 h-5" />
              </div>
              <div>
                <h3 className="text-xl font-bold text-slate-900">Doctor Visit Clinical Brief</h3>
                <p className="text-xs text-slate-500">Synthesized for physician review</p>
              </div>
            </div>

            <div className="flex items-center gap-2 print:hidden">
              <button
                onClick={handleCopy}
                className="px-3.5 py-2 rounded-xl border border-slate-200 hover:border-slate-300 bg-white text-xs font-semibold text-slate-700 flex items-center gap-1.5 transition active:scale-95 shadow-xs"
              >
                {copied ? (
                  <>
                    <Check className="w-4 h-4 text-emerald-600" />
                    <span className="text-emerald-700">Copied!</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-4 h-4 text-slate-500" />
                    <span>Copy Brief</span>
                  </>
                )}
              </button>

              <button
                onClick={handlePrint}
                className="px-3.5 py-2 rounded-xl bg-slate-900 hover:bg-slate-800 text-white text-xs font-semibold flex items-center gap-1.5 transition active:scale-95 shadow-xs"
              >
                <Printer className="w-4 h-4" />
                <span>Print</span>
              </button>
            </div>
          </div>

          {/* Printable Document Body */}
          <div className="space-y-6 text-sm text-slate-800 font-sans">
            {/* Header info */}
            <div className="bg-slate-50 border border-slate-200 rounded-xl p-4.5">
              <div className="flex items-center justify-between mb-2">
                <span className="text-xs font-bold uppercase tracking-wider text-teal-800">
                  Patient Summary
                </span>
                <span className="text-xs font-mono text-slate-500">ID: {elder.id}</span>
              </div>
              <div className="text-lg font-bold text-slate-900">{elder.name}</div>
              <div className="text-xs text-slate-600 mt-0.5">
                Age {elder.age} • Blood Group: <strong className="text-rose-600">{elder.bloodGroup}</strong> • Residence: {elder.residence}
              </div>
              <div className="text-xs text-rose-700 font-semibold mt-2 flex items-center gap-1.5">
                <AlertCircle className="w-4 h-4 text-rose-600" />
                Allergies: {elder.allergies.join(", ")} (High Sensitivity)
              </div>
            </div>

            {/* Appointment detail */}
            <div>
              <div className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-2">
                Consultation Context
              </div>
              <div className="border border-slate-200 rounded-xl p-4 space-y-1 text-xs sm:text-sm">
                <div>
                  <strong>Doctor:</strong> {appt?.doctorName || "Dr. Arvind Swaminathan"} ({appt?.specialty})
                </div>
                <div>
                  <strong>Hospital:</strong> {appt?.hospital}
                </div>
                <div>
                  <strong>Date:</strong> {apptDateFormatted}
                </div>
                <div className="text-slate-600 pt-1">
                  <strong>Visit Focus:</strong> {appt?.notes}
                </div>
              </div>
            </div>

            {/* Prescriptions */}
            <div>
              <div className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-2">
                Verified Current Prescriptions ({state.medications.filter((m) => m.active).length} Active)
              </div>
              <div className="border border-slate-200 rounded-xl overflow-hidden">
                <table className="w-full text-left text-xs">
                  <thead className="bg-slate-50 border-b border-slate-200 text-slate-600 font-semibold">
                    <tr>
                      <th className="p-2.5">Medication</th>
                      <th className="p-2.5">Dosage</th>
                      <th className="p-2.5">Scheduled</th>
                      <th className="p-2.5">Meal Timing</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100">
                    {state.medications
                      .filter((m) => m.active)
                      .map((med) => (
                        <tr key={med.id}>
                          <td className="p-2.5 font-bold text-slate-900">{med.name}</td>
                          <td className="p-2.5 text-slate-600">{med.dosage}</td>
                          <td className="p-2.5 text-teal-700 font-mono font-medium">
                            {med.scheduledTimes.join(", ")}
                          </td>
                          <td className="p-2.5 text-slate-600">{med.instructions}</td>
                        </tr>
                      ))}
                  </tbody>
                </table>
              </div>
            </div>

            {/* Checklist */}
            <div>
              <div className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-2">
                Care Circle Discussion Checklist
              </div>
              <ul className="space-y-2 border border-slate-200 rounded-xl p-4">
                {(appt?.checklistQuestions || []).map((q, idx) => (
                  <li key={idx} className="flex items-start gap-2.5 text-xs sm:text-sm">
                    <span className="w-4 h-4 border border-slate-400 rounded-xs mt-0.5 shrink-0" />
                    <span>{q}</span>
                  </li>
                ))}
              </ul>
            </div>
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  );
};
